using System.Text;
using System.Text.Json;
using System.Text.Json.Serialization.Metadata;
using Wtt.App.Bridge;

namespace Wtt.BridgeTypes;

/// <summary>
/// The TypeScript declarations of the bridge contract. Every name is taken from the shared serializer options — a
/// property as they write it, an enum value as they serialize it — so what the UI compiles against is what crosses
/// the bridge. A type the contract uses that this writer does not know stops the build instead of being guessed.
/// </summary>
internal sealed class Declarations
{
    private const string Header =
        "// Generated by Wtt.BridgeTypes from the bridge contract in src/Wtt.App/Bridge. Do not edit: every build rewrites it.";

    private static readonly Dictionary<Type, string> Primitives = new()
    {
        [typeof(string)] = "string",
        [typeof(bool)] = "boolean",
        [typeof(int)] = "number",
        [typeof(long)] = "number",
        [typeof(decimal)] = "number",
        [typeof(double)] = "number",
        [typeof(object)] = "unknown",
        [typeof(JsonElement)] = "unknown",
    };

    private readonly JsonSerializerOptions options;
    private readonly List<Type> declared = [];

    private Declarations(JsonSerializerOptions options) => this.options = options;

    public static string Write(JsonSerializerOptions options, IReadOnlyList<BridgeMessage> messages, IReadOnlyList<Type> envelopes, Type refusalCodes)
    {
        var declarations = new Declarations(options);
        var text = new StringBuilder(Header).AppendLine().AppendLine();

        text.AppendLine("/** Each message type the UI may send: the payload it sends and the result it is answered with. */");
        text.AppendLine("export interface BridgeMessages {");
        foreach (var message in messages)
        {
            text.AppendLine($"  {Quoted(message.Type)}: {{ request: {declarations.Reference(message.Request)}; result: {declarations.Reference(message.Result)} }};");
        }

        text.AppendLine("}");
        foreach (var envelope in envelopes)
        {
            declarations.Reference(envelope);
        }

        declarations.Reference(refusalCodes);
        for (var i = 0; i < declarations.declared.Count; i++)
        {
            text.AppendLine();
            text.Append(declarations.Declaration(declarations.declared[i]));
        }

        return text.ToString().ReplaceLineEndings("\n");
    }

    private static string Quoted(string text) => JsonSerializer.Serialize(text);

    /// <summary>How a property's type reads in TypeScript; an enum or record is declared once, under its C# name.</summary>
    private string Reference(Type type)
    {
        if (Nullable.GetUnderlyingType(type) is { } underlying)
        {
            return $"{Reference(underlying)} | null";
        }

        if (Primitives.TryGetValue(type, out var primitive))
        {
            return primitive;
        }

        var info = options.GetTypeInfo(type);
        if (info.Kind == JsonTypeInfoKind.Enumerable)
        {
            var element = Reference(info.ElementType!);
            return element.Contains(' ', StringComparison.Ordinal) ? $"({element})[]" : $"{element}[]";
        }

        if (type.IsEnum || info.Kind == JsonTypeInfoKind.Object)
        {
            if (!declared.Contains(type))
            {
                declared.Add(type);
            }

            return type.Name;
        }

        throw new NotSupportedException($"The bridge contract uses {type}, which has no TypeScript declaration here.");
    }

    private string Declaration(Type type)
    {
        var text = new StringBuilder();
        if (type.IsEnum)
        {
            var values = Enum.GetValues(type).Cast<object>().Select(value => JsonSerializer.Serialize(value, type, options));
            text.AppendLine($"export type {type.Name} = {string.Join(" | ", values)};");
            return text.ToString();
        }

        var properties = options.GetTypeInfo(type).Properties;
        if (properties.Count == 0)
        {
            text.AppendLine($"export type {type.Name} = Record<string, never>;");
            return text.ToString();
        }

        text.AppendLine($"export interface {type.Name} {{");
        foreach (var property in properties)
        {
            var optional = property.AssociatedParameter is { HasDefaultValue: true } ? "?" : string.Empty;
            var reference = Reference(property.PropertyType);
            var nullable = property.IsGetNullable && Nullable.GetUnderlyingType(property.PropertyType) is null ? " | null" : string.Empty;
            text.AppendLine($"  {property.Name}{optional}: {reference}{nullable};");
        }

        text.AppendLine("}");
        return text.ToString();
    }
}
